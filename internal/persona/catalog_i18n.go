package persona

// Translations of the catalog's user-facing text. Turkish (the fields on
// Character and Feature themselves) is the base; every other language the
// desktop app offers has an entry here. TestCatalogIsTranslated keeps the
// two in step when a character or feature is added. Prompts stay English:
// the model reads them, the user does not.

// Text is a catalog entry's name and description in one language.
type Text struct {
	Name    string `json:"name"`
	Summary string `json:"summary,omitempty"`
	// Category is filled on characters only.
	Category string `json:"category,omitempty"`
}

// Langs are the non-base languages every entry must be translated into.
var Langs = []string{"en", "de", "fr", "es", "it", "pt", "ru", "ja", "ko", "zh", "ar", "nl", "pl", "sv", "hi"}

type t2 [2]string

func init() {
	for i := range Characters {
		c := &Characters[i]
		c.I18n = map[string]Text{}
		for _, lang := range Langs {
			if tx, ok := characterText[lang][c.ID]; ok {
				c.I18n[lang] = Text{Name: tx[0], Summary: tx[1], Category: categoryText[lang][c.Category]}
			}
		}
	}
	for i := range Features {
		f := &Features[i]
		f.I18n = map[string]Text{}
		for _, lang := range Langs {
			if tx, ok := featureText[lang][f.Key]; ok {
				f.I18n[lang] = Text{Name: tx[0], Summary: tx[1]}
			}
		}
	}
}

